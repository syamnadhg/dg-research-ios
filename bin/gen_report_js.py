#!/usr/bin/env python3
"""Generate the Swift half's copy of the extraction JavaScript from the Python half.

⚠ **Generated, not retyped.** The script walks a shape nobody would guess — the report lives in
`metadata.chatgpt_sdk.widget_state`, which is itself a JSON *string*, under
`report_message.content.parts` — and two hand-maintained copies of that walk will diverge. The
divergence presents as *"extraction works on Safari and returns nothing in the app"*, which reads as
a surface problem and is not one. This repo has already paid for that once, with selectors.

    .venv/bin/python bin/gen_report_js.py            # write
    .venv/bin/python bin/gen_report_js.py --check    # fail if stale (the gate uses this)
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from emubackend import report_extract as rx  # noqa: E402

OUT = REPO / "ios" / "Sources" / "SuperResearchDeviceCore" / "ReportExtractJS.swift"

HEADER = '''// GENERATED by bin/gen_report_js.py — DO NOT EDIT.
//
// The extraction JavaScript, generated from `emubackend/report_extract.py` so the two halves cannot
// drift. Edit the Python and re-run the generator; `bin/all_gates.sh` fails if this file is stale.

extension ReportExtract {
'''


def swift_literal(name: str, js: str) -> str:
    """A Swift raw string with enough pound signs to survive whatever the JS contains."""
    pounds = "#"
    while pounds + '"' in js or '"' + pounds in js:
        pounds += "#"
    # ⚠ The closing delimiter sits at column 0, not indented to match the declaration. Swift strips
    # the closing delimiter's indentation from every line and REFUSES any line indented less than
    # it — and this JS starts at column 0. Indenting the delimiter to look tidy is a compile error
    # on every line of the payload.
    return (f'    static let {name} = {pounds}"""\n'
            f'{js.rstrip()}\n'
            f'"""{pounds}\n')


def render() -> str:
    return (HEADER
            + swift_literal("startJS", rx.START_JS.strip())
            + "\n"
            + swift_literal("pollJS", rx.POLL_JS.strip())
            + "}\n")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the file is stale")
    args = ap.parse_args()

    want = render()
    if args.check:
        have = OUT.read_text() if OUT.exists() else ""
        if have != want:
            print(f"⛔ {OUT.relative_to(REPO)} is STALE — the two halves of the extractor have "
                  f"drifted. Run: .venv/bin/python bin/gen_report_js.py", file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(REPO)} is up to date")
        return 0

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(want)
    print(f"wrote {OUT.relative_to(REPO)} ({len(want)} chars)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
